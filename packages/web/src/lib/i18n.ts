const dictionaries: Record<Locale, Dict> = { ar, fr, en, zh };

// Fallback: keys not present in the selected locale fall back to English, then Arabic.
const FALLBACKS: Locale[] = ['en', 'ar'];

export function translate(locale: Locale, key: string): string {
  const dict = dictionaries[locale];
  if (dict && key in dict) return dict[key];
  for (const fb of FALLBACKS) {
    if (fb === locale) continue;
    const fdict = dictionaries[fb];
    if (fdict && key in fdict) return fdict[key];
  }
  return key;
}